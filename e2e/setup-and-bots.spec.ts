import { expect, test } from "@playwright/test";
import { resetData, sql } from "./support";

test.beforeEach(resetData);

test("compact job handoff, Settings prompt, and setup navigation", async ({ page, context }) => {
  await page.addInitScript(() => { (window as unknown as { hiremeLaunches: string[] }).hiremeLaunches = []; document.addEventListener("click", event => { const a = (event.target as Element)?.closest?.("a"); if (a && /^(grokbot|claude|hireme-bot):/.test(a.href)) { event.preventDefault(); (window as unknown as { hiremeLaunches: string[] }).hiremeLaunches.push(a.href); } }, true); });
  await context.grantPermissions(["clipboard-read", "clipboard-write"]);
  const [app] = await sql<{ id: string; company: string; role: string }>('SELECT a.id, a.company, a.role FROM "Application" a WHERE NOT a."awaitingReview" AND EXISTS (SELECT 1 FROM "Document" d WHERE d."applicationId" = a.id) LIMIT 1');
  await page.goto("/settings?section=agent");
  await page.getByLabel("Prompt template (optional)").fill("My format: {{role}} at {{company}}. Files: {{zip_url}}");
  await page.getByLabel("Prompt template (optional)").blur();
  await expect.poll(async () => (await sql<{ value: string }>('SELECT value FROM "Setting" WHERE key = $1', ["applyBotPromptTemplate"]))[0]?.value).toBe("My format: {{role}} at {{company}}. Files: {{zip_url}}");
  await page.getByLabel("OpenBot handoff", { exact: true }).selectOption("mac-helper");
  await expect.poll(async () => (await sql<{ value: string }>('SELECT value FROM "Setting" WHERE key = $1', ["openbotLaunchMode"]))[0]?.value).toBe("mac-helper");
  await page.reload();
  await expect(page.getByLabel("Prompt template (optional)")).toHaveValue("My format: {{role}} at {{company}}. Files: {{zip_url}}");
  await page.goto(`/applications/${app.id}`);
  const selector = page.getByRole("combobox", { name: "Application bot", exact: true });
  await expect(selector).toBeVisible();
  expect((await selector.boundingBox())!.width).toBeLessThanOrEqual(180);
  await expect(page.getByRole("button", { name: "Save to Google Drive", exact: true })).toHaveCount(0);
  await expect(page.getByText("Connect Google Drive in Settings to save application packets automatically.", { exact: false })).toBeVisible();
  await selector.selectOption("openbot");
  await page.getByRole("button", { name: "Copy bot prompt", exact: true }).click();
  const prompt = await page.evaluate(() => navigator.clipboard.readText());
  expect(prompt).toContain(`/api/apply-packets/${app.id}`);
  expect(prompt).toContain("OpenBot");
  expect(prompt).toContain(`My format: ${app.role} at ${app.company}. Files:`);
  expect(prompt).toContain("HireMe");
  await page.getByRole("link", { name: "Apply with bot", exact: true }).click();
  const helperLaunch = new URL(await page.evaluate(() => (window as unknown as { hiremeLaunches: string[] }).hiremeLaunches.at(-1)!));
  expect(helperLaunch.protocol).toBe("hireme-bot:");
  expect(helperLaunch.searchParams.get("message")).toContain(`/api/apply-packets/${app.id}`);
  expect(helperLaunch.searchParams.get("message")).toContain("never submit without my explicit approval");
  await selector.selectOption("grok");
  await page.getByRole("link", { name: "Apply with bot", exact: true }).click();
  const launched = await page.evaluate(() => (window as unknown as { hiremeLaunches: string[] }).hiremeLaunches.at(-1)!);
  const grok = new URL(launched);
  expect(grok.protocol).toBe("grokbot:");
  expect(grok.searchParams.get("text")).toContain(`/api/apply-packets/${app.id}`);
  expect(grok.searchParams.get("text")).toContain("bot-prompt.md");
  expect(grok.searchParams.get("text")!.length).toBeLessThanOrEqual(1000);
  expect(grok.searchParams.get("text")).not.toMatch(/[\r\n\t]/);
  await selector.selectOption("openbot");
  await page.screenshot({ path: "test-results/job-controls-desktop.png", fullPage: false });
  await page.getByRole("link", { name: "Bot settings", exact: true }).click();
  await expect(page.getByLabel("Application for prompt preview")).toHaveValue(app.id);
  await page.getByRole("button", { name: "Preview OpenBot prompt", exact: true }).click();
  await expect(page.getByLabel("OpenBot full application prompt")).toHaveValue(/^My format:/);
  await expect(page.getByLabel("OpenBot full application prompt")).toHaveValue(/OpenBot/);
  await expect(page.getByLabel("OpenBot full application prompt")).toHaveValue(new RegExp(app.id));
  await page.screenshot({ path: "test-results/bot-settings-desktop.png", fullPage: false });
  await page.goto("/settings?section=setup");
  await expect(page.getByRole("heading", { name: "Setup & health", exact: true })).toBeVisible();
  await expect(page.getByText("Live check passed", { exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Configure Google Drive auto-save", exact: true })).toHaveAttribute("href", "/settings?section=google");
  await page.screenshot({ path: "test-results/setup-desktop.png", fullPage: false });
  await page.getByRole("link", { name: "Configure Google Drive auto-save", exact: true }).click();
  await page.getByRole("switch", { name: "Save application packets automatically", exact: true }).click();
  await expect.poll(async () => (await sql<{ value: string }>('SELECT value FROM "Setting" WHERE key = $1', ["driveAutoSave"]))[0]?.value).toBe("false");
  await page.reload();
  await expect(page.getByText("Connect Google Drive in Settings to save application packets automatically.", { exact: false })).toHaveCount(0);
  await page.getByRole("button", { name: "Collapse sidebar", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`/applications/${app.id}`);
  await expect(selector).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/job-controls-mobile.png", fullPage: false });
});
